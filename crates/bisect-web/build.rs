use std::{env, fs, io, path::PathBuf};

fn main() -> io::Result<()> {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let source = manifest.join("../../web/lab").canonicalize()?;
    // Track the directory as well as each file so additions/removals rebuild the
    // embedded set. No JavaScript executes during discovery or compilation.
    println!("cargo:rerun-if-changed={}", source.display());
    let mut names = Vec::new();
    for entry in fs::read_dir(&source)? {
        let entry = entry?;
        if entry.path().extension().and_then(|s| s.to_str()) != Some("js") {
            continue;
        }
        if !entry.file_type()?.is_file() {
            return Err(io::Error::new(io::ErrorKind::InvalidData, "Browser JavaScript assets must be regular files."));
        }
        let name = entry.file_name().into_string().map_err(|_| io::Error::new(io::ErrorKind::InvalidData, "Browser asset name is not UTF-8."))?;
        if !name.bytes().all(|b| b.is_ascii_alphanumeric() || b"._-".contains(&b)) {
            return Err(io::Error::new(io::ErrorKind::InvalidData, "Browser asset name is not portable."));
        }
        println!("cargo:rerun-if-changed={}", entry.path().display());
        // These two modules already have explicit native routes/catalog writes.
        if name != "lab.js" && name != "static.js" {
            names.push(name);
        }
    }
    names.sort();
    let mut generated = String::from("// Generated by bisect-web/build.rs from public web/lab JavaScript.\npub const INPUT_ASSETS: &[(&str, &str)] = &[\n");
    for name in names {
        generated.push_str(&format!("    (\"{name}\", include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/../../web/lab/{name}\"))),\n"));
    }
    generated.push_str("];\n");
    fs::write(PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("input_assets.rs"), generated)?;
    Ok(())
}
