import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';

// A containing workflow reuses its manifest; standalone analysis generates it.
// All output bytes and remaining record fields must still match exactly.
export function assertWorkflowAnalysis(workflow,analysis,planText,contextText){
 const hash=text=>createHash('sha256').update(text).digest('hex');
 for(const [name,text]of Object.entries(analysis.files)){
  const path=['plan.rplan','context.rctx','manifest.json','analysis-package.json'].includes(name)?name:'analysis/'+name;
  const actual=Buffer.from(workflow.files_base64[path],'base64').toString();
  if(name!=='analysis-package.json'){assert.equal(actual,text,path);continue;}
  const record=JSON.parse(text),manifest=record.steps.filter(step=>step.name==='manifest');
  assert.equal(manifest.length,1);assert.equal(manifest[0].population_balance_evaluated,true);
  assert.deepEqual(Object.keys(manifest[0]).sort(),['context_source_sha256','name','plan_source_sha256','population_balance_evaluated','scope','status']);
  assert.equal(manifest[0].status,'computed');assert.equal(typeof manifest[0].scope,'string');assert(manifest[0].scope.length>0);
  assert.equal(manifest[0].plan_source_sha256,hash(planText));assert.equal(manifest[0].context_source_sha256,hash(contextText));
  const expected={...record,steps:record.steps.map(step=>step.name==='manifest'?{name:'manifest',status:'computed',scope:'Manifest generated by the containing native State workflow from the same accepted plan/context and selected source.'}:step)};
  assert.deepEqual(JSON.parse(actual),expected);assert.deepEqual(workflow.stages.find(stage=>stage.name==='analysis').steps,expected.steps);
 }
}
